"""Finds non-dev toolchain registrations for types a module doesn't own.

A module owns the types in its own repo and in repos generated by its module extensions. Registrations for any other type
inject toolchains into the builds of all of the module's dependents.
"""

import ast
import functools
import json
import pathlib
import shutil
import subprocess
import tempfile

from typing import NamedTuple

BAZEL_TIMEOUT_SECONDS = 600
MAX_ALIAS_CHAIN_LENGTH = 32
WILDCARD_SUFFIXES = ("/...", ":all", ":*", ":all-targets")


class ForeignRegistration(NamedTuple):
    line: int
    pattern: str
    toolchain_types: list


class UnanalyzedRegistration(NamedTuple):
    line: int
    reason: str


class AnalysisError(Exception):
    """Raised when it can't be determined which toolchain types a registration applies to."""


def find_registrations(module_dot_bazel):
    """Returns the non-dev registrations in a MODULE.bazel file.

    Returns:
      A tuple of a list of (line, pattern) pairs and a list of the lines of calls that can't be analyzed statically.
    """
    registrations = []
    unsupported_lines = []
    for node in ast.walk(ast.parse(module_dot_bazel)):
        if not (isinstance(node, ast.Call) and getattr(node.func, "id", None) == "register_toolchains"):
            continue
        dev_dependency = next((k.value for k in node.keywords if k.arg == "dev_dependency"), ast.Constant(False))
        if not isinstance(dev_dependency, ast.Constant):
            unsupported_lines.append(node.lineno)
        elif not dev_dependency.value:
            for arg in node.args:
                if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                    registrations.append((arg.lineno, arg.value))
                else:
                    unsupported_lines.append(arg.lineno)
    return sorted(registrations), sorted(unsupported_lines)


def canonicalize_pattern(pattern, own_repo, repo_mapping):
    """Rewrites a target pattern from a module's MODULE.bazel to be valid in any repo."""
    if pattern.startswith("@@"):
        return pattern
    if pattern.startswith("//"):
        return f"@@{own_repo}{pattern}"
    apparent_repo, separator, rest = pattern.removeprefix("@").partition("//")
    if not separator or apparent_repo not in repo_mapping:
        raise AnalysisError(f"can't resolve the repo of {pattern} in the module's repo mapping")
    return f"@@{repo_mapping[apparent_repo]}//{rest}"


def owning_module(label):
    """Returns the name of the module that owns the repo of the given canonical label."""
    canonical_repo = label.removeprefix("@@").partition("//")[0]
    # Canonical repo names are "<module>+", "<module>+<version>" or "<module>+[<version>]+<extension>+<repo>", where
    # <module> defines the extension. This format isn't an API, but module names can't contain "+".
    return canonical_repo.partition("+")[0]


def get_label_attr(rule, name):
    for attr in rule["attribute"]:
        if attr["name"] == name:
            if "stringValue" not in attr:
                raise AnalysisError(f"{rule['name']} doesn't have a constant value for its {name} attribute")
            return attr["stringValue"]
    raise AnalysisError(f"{rule['name']} doesn't have a {name} attribute")


class RegistrationAnalyzer:
    """Determines which toolchain types registrations apply to."""

    def __init__(self, query_rules):
        """Args: query_rules: Function that returns the parsed rules matching a Bazel query expression."""
        self._query_rules = query_rules
        self._resolve_alias = functools.cache(self._resolve_alias_uncached)

    def _resolve_alias_uncached(self, label):
        for _ in range(MAX_ALIAS_CHAIN_LENGTH):
            rules = self._query_rules(f'"{label}"')
            if len(rules) != 1:
                raise AnalysisError(f"{label} isn't a rule target")
            if rules[0]["ruleClass"] != "alias":
                return rules[0]
            label = get_label_attr(rules[0], "actual")
        raise AnalysisError(f"too many aliases starting at {label}")

    def toolchain_types(self, pattern):
        """Returns the set of canonical toolchain type labels that the given canonical pattern registers toolchains for.

        Like Bazel, only considers aliases if they are named explicitly.
        """
        kinds = "toolchain" if pattern.endswith(WILDCARD_SUFFIXES) else "toolchain|alias"
        types = set()
        for rule in self._query_rules(f'kind("^({kinds}) rule$", "{pattern}")'):
            toolchain = self._resolve_alias(rule["name"])
            types.add(self._resolve_alias(get_label_attr(toolchain, "toolchain_type"))["name"])
        return types


class Bazel:
    """Runs Bazel in a workspace whose root module depends on the module to be checked."""

    def __init__(self, registry_root, module_name, version, root):
        self._output_base = root / "output_base"
        self._workspace = root / "workspace"
        self._workspace.mkdir()
        if (registry_root / ".bazelversion").exists():
            shutil.copy(registry_root / ".bazelversion", self._workspace)
        (self._workspace / "MODULE.bazel").write_text(f"bazel_dep(name = '{module_name}', version = '{version}')\n")
        (self._workspace / ".bazelrc").write_text(
            f"common --registry={registry_root.as_uri()}\ncommon --lockfile_mode=off\n"
        )

    def _run(self, *args):
        try:
            return subprocess.run(
                ["bazel", "--nosystem_rc", "--nohome_rc", f"--output_base={self._output_base}", *args],
                cwd=self._workspace,
                capture_output=True,
                text=True,
                timeout=BAZEL_TIMEOUT_SECONDS,
            )
        except (OSError, subprocess.TimeoutExpired) as e:
            raise AnalysisError(f"bazel {args[0]} failed: {e}")

    def _run_checked(self, *args):
        result = self._run(*args)
        if result.returncode != 0:
            errors = [line for line in result.stderr.splitlines() if line.startswith("ERROR")]
            raise AnalysisError(f"bazel {args[0]} failed: {' '.join(errors)}")
        return result.stdout

    def repo_mapping(self, canonical_repo):
        return json.loads(self._run_checked("mod", "dump_repo_mapping", canonical_repo))

    def query_rules(self, expression):
        output = self._run_checked("query", "--output=streamed_jsonproto", "--consistent_labels", expression)
        targets = (json.loads(line) for line in output.splitlines())
        return [target["rule"] for target in targets if target["type"] == "RULE"]

    def shutdown(self):
        try:
            self._run("shutdown")
        except AnalysisError:
            pass


def analyze_registrations(registry_root, module_name, version, run_module_code):
    """Finds the module's non-dev registrations for toolchain types it doesn't own.

    Args:
      registry_root: The root path of the registry.
      module_name: The name of the module.
      version: The version of the module.
      run_module_code: Whether non-dev registrations may be expanded, which runs the module's extensions and repo rules.

    Returns:
      A tuple of a list of ForeignRegistrations and a list of UnanalyzedRegistrations.
    """
    registry_root = pathlib.Path(registry_root).resolve()
    module_dot_bazel = registry_root / "modules" / module_name / version / "MODULE.bazel"
    registrations, unsupported_lines = find_registrations(module_dot_bazel.read_text())
    unanalyzed = [UnanalyzedRegistration(line, "it doesn't use string literals") for line in unsupported_lines]
    if not registrations:
        return [], unanalyzed
    if not run_module_code:
        reason = "running module code requires the other validations to pass without a BCR maintainer review"
        return [], unanalyzed + [UnanalyzedRegistration(line, reason) for line, _ in registrations]

    foreign = []
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as root:
        bazel = Bazel(registry_root, module_name, version, pathlib.Path(root))
        try:
            analyzer = RegistrationAnalyzer(bazel.query_rules)
            try:
                own_repo = bazel.repo_mapping("")[module_name]
                repo_mapping = bazel.repo_mapping(own_repo)
            except AnalysisError as e:
                return [], unanalyzed + [UnanalyzedRegistration(line, str(e)) for line, _ in registrations]
            for line, pattern in registrations:
                try:
                    types = analyzer.toolchain_types(canonicalize_pattern(pattern, own_repo, repo_mapping))
                except AnalysisError as e:
                    unanalyzed.append(UnanalyzedRegistration(line, str(e)))
                    continue
                foreign_types = sorted(t for t in types if owning_module(t) != module_name)
                if foreign_types:
                    foreign.append(ForeignRegistration(line, pattern, foreign_types))
        finally:
            bazel.shutdown()
    return foreign, unanalyzed
