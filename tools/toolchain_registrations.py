"""Checks that a module's non-dev toolchain registrations are for toolchain types it owns.

A module owns the types in its own repo and in repos generated by its module extensions. A non-dev registration for any
other type injects toolchains into the builds of all of the module's dependents.

Bazel expands the registrations with `bazel mod show_toolchains`, which runs the module's extensions and repo rules and
reports the module that owns the type of each toolchain. Bazel runs through Bazelisk with the registry's .bazelversion,
which has to be a version that supports this command. The BCR presubmit runs this script after
the build and tests of one of the module's anonymous module tasks, in the same workspace and with the same startup
options. Without --workspace, it creates its own anonymous module workspace.

Exits with 1 if the module registers toolchains for types it doesn't own.
"""

import argparse
import ast
import contextlib
import json
import os
import pathlib
import re
import subprocess
import sys
import tempfile
import time

from typing import NamedTuple

DISCUSSION_URL = "https://github.com/bazelbuild/bazel/discussions/32428"
SKIP_COMMAND = "@bazel-io skip_check toolchain_registrations"
MODULE_TIMEOUT_SECONDS = 900
SHUTDOWN_TIMEOUT_SECONDS = 60
MAX_ERROR_LINES = 5
TRACEBACK_LOCATION_RE = re.compile(r'^\s*File "([^"]+)", line (\d+), column (\d+)')
# Matches the path of the external repos directory in Bazel's output, so that errors don't depend on the output base.
EXTERNAL_PATH_RE = re.compile(r"(?:file://)?(?:[A-Za-z]:)?/[^\s'\"]*?/external/")
# Prefixes of lines in Bazel's output that don't continue an error message. Tabs indent source lines in tracebacks.
NON_MESSAGE_PREFIXES = (
    "\t",
    "    currently ",
    "    Fetching ",
    "Analyzing:",
    "Computing main repo mapping:",
    "DEBUG:",
    "Fetching ",
    "INFO:",
    "Loading:",
    "WARNING:",
)


class AnalysisError(Exception):
    """Raised when it can't be determined which toolchain types a registration applies to."""


class Call(NamedTuple):
    """A register_toolchains call that may not be a dev dependency."""

    line: int
    end_line: int
    # The string literal arguments.
    patterns: list
    # The source code of the other arguments.
    non_literal_args: list
    # Whether dev_dependency is a literal, which means that the call isn't a dev dependency.
    dev_dependency_known: bool = True


class CallResult(NamedTuple):
    call: Call
    # The patterns that were analyzed.
    patterns: list
    # Maps each pattern that registers toolchains for types the module doesn't own to these types.
    foreign: dict
    # (subject, message) pairs explaining why (parts of) the call couldn't be analyzed. The subject is a pattern or None.
    problems: list


class ModuleResult(NamedTuple):
    name: str
    version: str
    path: str
    calls: list

    @property
    def has_findings(self):
        return any(call.foreign for call in self.calls)

    @property
    def is_incomplete(self):
        return any(call.problems for call in self.calls)

    @property
    def status(self):
        if not self.calls:
            return "no non-dev registrations"
        statuses = []
        if self.has_findings:
            statuses.append("registers toolchains for types it doesn't own")
        if self.is_incomplete:
            statuses.append("couldn't be fully analyzed")
        return ", ".join(statuses) or "clean"


def find_registration_calls(module_dot_bazel):
    """Returns the register_toolchains calls in a MODULE.bazel file that may not be dev dependencies."""
    calls = []
    for node in ast.walk(ast.parse(module_dot_bazel)):
        if not (isinstance(node, ast.Call) and getattr(node.func, "id", None) == "register_toolchains"):
            continue
        dev_dependency = next((k.value for k in node.keywords if k.arg == "dev_dependency"), ast.Constant(False))
        if isinstance(dev_dependency, ast.Constant) and dev_dependency.value:
            continue
        patterns = []
        non_literal_args = []
        for arg in node.args:
            if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                patterns.append(arg.value)
            else:
                non_literal_args.append(ast.unparse(arg))
        calls.append(
            Call(node.lineno, node.end_lineno, patterns, non_literal_args, isinstance(dev_dependency, ast.Constant))
        )
    return sorted(calls)


def assign_patterns(calls, registered):
    """Returns a (call, patterns) pair for each call that registers toolchains for all dependents.

    Args:
      calls: The calls found in MODULE.bazel.
      registered: The patterns that Bazel registers for the module. These determine whether a call with a non-literal
        dev_dependency is a dev dependency. Registered patterns that aren't string literal arguments are attributed to
        the first call with other arguments.
    """
    registered_set = set(registered)
    literal_patterns = {pattern for call in calls for pattern in call.patterns}
    other_patterns = [pattern for pattern in dict.fromkeys(registered) if pattern not in literal_patterns]
    pairs = []
    for call in calls:
        patterns = [p for p in call.patterns if p in registered_set]
        if call.non_literal_args and other_patterns:
            patterns += other_patterns
            other_patterns = []
        if patterns:
            pairs.append((call, patterns))
    if other_patterns:
        # Bazel registers patterns that no call accounts for, so attribute them to the start of the file.
        pairs.append((Call(1, 1, [], []), other_patterns))
    return pairs


def strip_paths(line, path_prefixes):
    """Removes the registry and output base paths from a line of Bazel's output."""
    for prefix in path_prefixes:
        line = line.replace(prefix, "")
    return EXTERNAL_PATH_RE.sub("", line)


def describe_bazel_error(stderr, returncode, path_prefixes):
    """Returns the lines of Bazel's output that describe why it failed.

    Prefers the root causes of Starlark errors, prefixed with the innermost location outside of Bazel's builtins, over
    Bazel's ERROR lines. Joins messages that span multiple lines, such as those of fail().
    """
    causes = []
    errors = []
    location = None
    # The list whose last message unrecognized lines continue.
    current = None
    for line in stderr.splitlines():
        line = strip_paths(line, path_prefixes)
        if not line.strip():
            continue
        if match := TRACEBACK_LOCATION_RE.match(line):
            if not match[1].startswith("/virtual_builtins_bzl/"):
                location = f"{match[1]}:{match[2]}:{match[3]}"
            current = None
        elif line.startswith("Error"):
            causes.append(f"{location}: {line.strip()}" if location else line.strip())
            location = None
            current = causes
        elif line.startswith("ERROR: ") and not line.endswith("Traceback (most recent call last):"):
            errors.append(line.removeprefix("ERROR: ").strip())
            current = errors
        elif current is not None and not line.startswith(NON_MESSAGE_PREFIXES):
            current[-1] = f"{current[-1]} {line.strip()}"
        else:
            current = None
    lines = list(dict.fromkeys(causes or errors))
    if not lines:
        lines = [f"exit code {returncode}"] + [line for line in stderr.splitlines() if line.strip()][-MAX_ERROR_LINES:]
    return "\n".join(lines[:MAX_ERROR_LINES])


class Bazel:
    """Runs Bazel in a workspace whose root module depends on the module to be checked."""

    def __init__(self, workspace, startup_options, timeout_seconds, path_prefixes=(), bazel_version=None):
        self._workspace = workspace
        # Overrides the version of the presubmit job that ran in the workspace.
        self._env = {**os.environ, "USE_BAZEL_VERSION": bazel_version} if bazel_version else None
        self._startup_options = list(startup_options)
        self._timeout_seconds = timeout_seconds
        self._deadline = time.monotonic() + timeout_seconds
        self._path_prefixes = list(path_prefixes)

    def _run(self, *args, timeout=None):
        if timeout is None:
            timeout = self._deadline - time.monotonic()
        try:
            if timeout <= 0:
                raise subprocess.TimeoutExpired(args, timeout)
            return subprocess.run(
                ["bazel", *self._startup_options, *args],
                cwd=self._workspace,
                capture_output=True,
                env=self._env,
                text=True,
                timeout=timeout,
            )
        except subprocess.TimeoutExpired:
            raise AnalysisError(f"the analysis took longer than {self._timeout_seconds} seconds")
        except OSError as e:
            raise AnalysisError(f"couldn't run Bazel: {e}")

    def show_toolchains(self, module_name):
        """Returns the module's key and registrations as `bazel mod show_toolchains` reports them in its JSON output.

        Bazel only reports non-dev registrations of a non-root module. Error messages are stripped of paths.
        """
        result = self._run("mod", "show_toolchains", module_name, "--output=json")
        # Bazel prints all results before it fails because of registrations that it couldn't analyze.
        modules = [json.loads(line) for line in result.stdout.splitlines()]
        if not modules:
            if "Invalid subcommand" in result.stderr:
                raise AnalysisError("this Bazel version doesn't support `bazel mod show_toolchains`")
            raise AnalysisError(describe_bazel_error(result.stderr, result.returncode, self._path_prefixes))
        if len(modules) != 1:
            versions = ", ".join(module["module"] for module in modules)
            raise AnalysisError(f"the dependency graph contains multiple versions of {module_name}: {versions}")
        registrations = modules[0]["registrations"]
        for item in registrations + [target for r in registrations for target in r.get("targets", [])]:
            if "error" in item:
                item["error"] = strip_paths(item["error"], self._path_prefixes)
        return modules[0]["module"], registrations

    def shutdown(self):
        try:
            self._run("shutdown", timeout=SHUTDOWN_TIMEOUT_SECONDS)
        except AnalysisError:
            pass


def create_anonymous_workspace(registry_root, module_name, version, root):
    """Creates a workspace whose root module depends on the module and returns it with the startup options to use."""
    workspace = root / "workspace"
    workspace.mkdir()
    (workspace / "MODULE.bazel").write_text(f"bazel_dep(name = '{module_name}', version = '{version}')\n")
    (workspace / ".bazelrc").write_text(f"common --registry={registry_root.as_uri()}\ncommon --lockfile_mode=off\n")
    return workspace, ["--nosystem_rc", "--nohome_rc", f"--output_base={root / 'output_base'}"]


def _analyze_calls(bazel, module_name, calls):
    try:
        module_key, registrations = bazel.show_toolchains(module_name)
    except AnalysisError as e:
        return [CallResult(call, [], {}, [(None, str(e))]) for call in calls]
    by_pattern = {}
    for registration in registrations:
        by_pattern.setdefault(registration["pattern"], registration)
    results = []
    for call, patterns in assign_patterns(calls, list(by_pattern)):
        result = CallResult(call, patterns, {}, [])
        for pattern in patterns:
            registration = by_pattern[pattern]
            if "error" in registration:
                result.problems.append((pattern, registration["error"]))
                continue
            foreign = set()
            for target in registration["targets"]:
                if "error" in target:
                    result.problems.append((pattern, target["error"]))
                elif target["toolchain_type_owner"] != module_key:
                    foreign.add(target["toolchain_type"])
            if foreign:
                result.foreign[pattern] = sorted(foreign)
        results.append(result)
    return results


def analyze_module(
    registry_root, module_name, version, workspace=None, startup_options=(), timeout_seconds=MODULE_TIMEOUT_SECONDS
):
    """Finds the module's non-dev registrations for toolchain types it doesn't own.

    Args:
      registry_root: The root of the registry.
      module_name: The name of the module.
      version: The version of the module.
      workspace: A workspace whose root module depends on the module. If None, creates one in a temporary directory.
      startup_options: The Bazel startup options to use in the given workspace.
      timeout_seconds: The time after which the remaining registrations are reported as incomplete.

    Only runs Bazel if the module has registrations that may not be dev dependencies.
    """
    registry_root = pathlib.Path(registry_root).resolve()
    path = pathlib.PurePosixPath("modules", module_name, version, "MODULE.bazel")
    try:
        calls = find_registration_calls((registry_root / path).read_text())
    except SyntaxError as e:
        line = e.lineno or 1
        problem = (None, f"can't parse the file: {e.msg}")
        return ModuleResult(module_name, version, str(path), [CallResult(Call(line, line, [], []), [], {}, [problem])])
    if not calls:
        return ModuleResult(module_name, version, str(path), [])
    path_prefixes = []
    for root in dict.fromkeys([registry_root, registry_root.resolve()]):
        path_prefixes += [f"{root.as_uri()}/", f"{root}/"]
    bazel_version_file = registry_root / ".bazelversion"
    bazel_version = bazel_version_file.read_text().strip() if bazel_version_file.exists() else None
    with contextlib.ExitStack() as stack:
        if workspace is None:
            root = pathlib.Path(stack.enter_context(tempfile.TemporaryDirectory(ignore_cleanup_errors=True)))
            workspace, startup_options = create_anonymous_workspace(registry_root, module_name, version, root)
            bazel = Bazel(workspace, startup_options, timeout_seconds, path_prefixes, bazel_version)
            stack.callback(bazel.shutdown)
        else:
            bazel = Bazel(pathlib.Path(workspace), startup_options, timeout_seconds, path_prefixes, bazel_version)
        results = _analyze_calls(bazel, module_name, calls)
    return ModuleResult(module_name, version, str(path), results)


def format_problems(problems):
    """Returns one line per distinct problem, listing the patterns it applies to."""
    subjects_by_message = {}
    for subject, message in problems:
        subjects_by_message.setdefault(message, []).append(subject)
    lines = []
    for message, subjects in subjects_by_message.items():
        subjects = [subject for subject in subjects if subject]
        lines.append(f"{', '.join(subjects)}: {message}" if subjects else message)
    return lines


def foreign_message(module_name, call_result):
    registrations = "\n".join(f"- {pattern}: {', '.join(types)}" for pattern, types in call_result.foreign.items())
    return (
        f"These registrations apply to all dependents of {module_name}, but the module doesn't own their toolchain"
        f" types:\n{registrations}\nAdd `dev_dependency = True` if only the module's own builds need them. Otherwise,"
        f" ask users to register them in their root module. If these registrations are intended, comment"
        f" `{SKIP_COMMAND}` on the PR. See {DISCUSSION_URL}."
    )


def incomplete_message(call_result):
    problems = "\n".join(f"- {problem}" for problem in format_problems(call_result.problems))
    return f"Couldn't determine which toolchain types this registers:\n{problems}"


def lines_of(call):
    return f"{call.line}" if call.line == call.end_line else f"{call.line}-{call.end_line}"


def format_report(result):
    lines = [f"{result.name}@{result.version}: {result.status}"]
    for call_result in result.calls:
        location = f"{result.path}:{lines_of(call_result.call)}"
        if call_result.foreign:
            lines.append(f"{location}: {foreign_message(result.name, call_result)}")
        if call_result.problems:
            lines.append(f"{location}: {incomplete_message(call_result)}")
    return "\n\n".join(lines)


def parse_module_version(value):
    name, separator, version = value.partition("@")
    if not separator or not name or not version:
        raise argparse.ArgumentTypeError(f"expected MODULE@VERSION, got {value}")
    return name, version


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--registry",
        default=".",
        help="Specify the root path of the registry (default: the current working directory).",
    )
    parser.add_argument(
        "--check",
        action="append",
        required=True,
        type=parse_module_version,
        metavar="MODULE@VERSION",
        help="Check the given module version. This flag can be repeated.",
    )
    parser.add_argument(
        "--workspace",
        help="Run Bazel in this workspace, whose root module depends on the module, instead of creating one. The root"
        " module can be an anonymous module or a test module. Requires exactly one --check.",
    )
    parser.add_argument(
        "--bazel_startup_option",
        action="append",
        default=[],
        help="A Bazel startup option to use with --workspace. This flag can be repeated.",
    )
    args = parser.parse_args(argv)
    if args.workspace and len(args.check) != 1:
        parser.error("--workspace requires exactly one --check")

    if os.getenv("BUILD_WORKSPACE_DIRECTORY"):
        os.chdir(os.getenv("BUILD_WORKSPACE_DIRECTORY"))
    findings = False
    for name, version in args.check:
        print(f"Checking the toolchain registrations of {name}@{version}...", flush=True)
        result = analyze_module(args.registry, name, version, args.workspace, args.bazel_startup_option)
        print(format_report(result), flush=True)
        findings |= result.has_findings
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
