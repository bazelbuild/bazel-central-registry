# Batched version of util/dofile.pl for Bazel.
#
# Processes multiple OpenSSL .in templates in a single Perl invocation,
# writing each result directly to its output file.  This avoids the
# per-template process-creation overhead that dominates on Windows.
#
# Usage: batch_dofile.pl --in=<template> --out=<output> [--in=... --out=...] ...
#
# Arguments of the form @<file> name a Bazel params file containing one
# argument per line; they are expanded in place.
#
# Must be invoked with -Mconfigdata.

use strict;
use warnings;

use FindBin;
use Symbol ();
use lib "$FindBin::Bin/perl";
use OpenSSL::fallback "$FindBin::Bin/../external/perl/MODULES.txt";
use OpenSSL::Template;

# Upstream loads oids_to_c with -Moids_to_c. It carries a leftover
# `use re 'debugcolor'`, which makes re.pm look up terminal colours through
# Term::Cap whenever the module is compiled; on Windows, where Term::Cap
# falls back to TERM=dumb, that prints "Use of uninitialized value in join"
# six times per load. Only the colours of regex debug output depend on it,
# so the lookup is stubbed out before the module is loaded (here and on
# every reload below).
BEGIN {
    require re;
    no warnings 'redefine';
    *re::setcolor = sub { };
}
use oids_to_c;

# OpenSSL renders every template in its own perl process. Some helper modules
# keep process-global state that would leak between templates when batched:
#   * OpenSSL::OID (used via oids_to_c) registers every OID it parses, and an
#     OID registered as a leaf by one .asn1 file silently becomes an arc once
#     another file uses it as a parent, changing what process_leaves() emits;
#   * OpenSSL::paramnames (4.1+) emits its #include preamble only on the first
#     produce_param_decoder() call in a process.
# To keep the per-process semantics, these modules are unloaded before each
# template; oids_to_c is loaded at startup and so is re-required,
# OpenSSL::paramnames is `use`d by the templates themselves.
my @RESET_MODULES = qw(oids_to_c OpenSSL::OID OpenSSL::paramnames);

sub reset_stateful_modules {
    for my $mod (@RESET_MODULES) {
        (my $file = "$mod.pm") =~ s{::}{/}g;
        next unless exists $INC{$file};
        delete $INC{$file};
        Symbol::delete_package($mod);
    }
    require oids_to_c;
}

die "You must run this script with -Mconfigdata\n"
    if !exists($config{target});

# Expand param files, if any.
my @args;
for my $arg (@ARGV) {
    if ($arg =~ /^@(.+)$/) {
        open(my $fh, '<', $1)
            or die "Can't open params file $1: $!\n";
        while (my $line = <$fh>) {
            $line =~ s/\r?\n$//;
            push @args, $line;
        }
        close $fh;
    } else {
        push @args, $arg;
    }
}

my @pairs;
my $i = 0;
while ($i < scalar(@args)) {
    my $arg = $args[$i];
    if ($arg =~ /^--in=(.+)$/) {
        my $in = $1;
        $i++;
        die "Expected --out=<path> after --in=$in\n"
            if $i >= scalar(@args) || $args[$i] !~ /^--out=(.+)$/;
        push @pairs, { in => $in, out => $1 };
    } else {
        die "Unexpected argument: $arg\n";
    }
    $i++;
}

die "No --in/--out pairs given\n" unless @pairs;

my @autowarntext = (
    "WARNING: do not edit!",
    "Generated by batch_dofile.pl"
);

my $failed = 0;
sub errorcallback {
    my %args = @_;
    print STDERR $args{error};
    $failed++;
    return undef;
}

my $prepend = <<"_____";
use File::Spec::Functions;
use lib '$FindBin::Bin/../Configurations';
use lib '$config{builddir}';
use platform;
_____

for my $pair (@pairs) {
    reset_stateful_modules();

    my $template = OpenSSL::Template->new(
        TYPE     => 'FILE',
        SOURCE   => $pair->{in},
        FILENAME => $pair->{in},
    );
    die "Couldn't create template for $pair->{in}: $Text::Template::ERROR\n"
        if !defined($template);

    my $result = $template->fill_in(
        TYPE     => 'FILE',
        SOURCE   => $pair->{in},
        FILENAME => $pair->{in},
        HASH     => {
            config       => \%config,
            target       => \%target,
            disabled     => \%disabled,
            withargs     => \%withargs,
            unified_info => \%unified_info,
            autowarntext => \@autowarntext,
        },
        BROKEN  => \&errorcallback,
        PREPEND => $prepend,
        PACKAGE => 'OpenSSL::safe',
    );
    exit 1 if $failed;

    open(my $fh, '>', $pair->{out})
        or die "Can't open $pair->{out}: $!\n";
    print $fh $result;
    close $fh;
}
